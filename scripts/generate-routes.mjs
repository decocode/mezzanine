// Prints nginx's list of allowed app routes, from the docs pages in site/siteStructure.ts and the
// Lab pages in site/lab/. The Docker build writes it to /etc/nginx/conf.d/routes.inc, which
// config/nginx.conf includes; any other path gets a real 404 status. Usage: node scripts/generate-routes.mjs
import { readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { labPaths } from './docs-rules.mjs'
import { sitePages } from '../site/siteStructure.ts'

const root = path.resolve(import.meta.dirname, '..')

function labSources(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) return labSources(file)
    return /\.tsx?$/.test(entry.name) ? [readFileSync(file, 'utf8')] : []
  })
}

export function appRoutes() {
  const lab = labSources(path.join(root, 'site/lab'))
  const paths = [...sitePages.map((page) => page.path), '/site/lab', ...labPaths({ labContent: '', pageContent: lab.join('\n') })]
  return [...new Set(paths)].sort()
}

export function routesConfig(routes = appRoutes()) {
  const escape = (route) => route.replace(/[.*+?^$()|[\]\\{}]/g, '\\$&')
  return [
    '# Generated by scripts/generate-routes.mjs from site/siteStructure.ts and site/lab/. Do not edit.',
    'map $uri $is_app_route {',
    '    default 0;',
    ...routes.map((route) => route === '/' ? '    ~^/?$ 1;' : `    ~^${escape(route)}/?$ 1;`),
    '}',
    '',
  ].join('\n')
}

if (import.meta.main) process.stdout.write(routesConfig())
